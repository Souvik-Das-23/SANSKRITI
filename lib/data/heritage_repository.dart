  static List<HeritagePlace> getAllPlaces() => List<HeritagePlace>.from(_places);

  static List<HeritagePlace> getPlacesByCategory(HeritageCategory category) {
    if (category == HeritageCategory.all) return getAllPlaces();
    return _places.where((p) => p.category == category).toList();
  }

  static HeritagePlace? getPlaceById(String id) {
    try {
      return _places.firstWhere((p) => p.id == id);
    } catch (_) {
      return null;
    }
  }

  static List<HeritagePlace> searchPlaces(String query) {
    if (query.trim().isEmpty) return getAllPlaces();
    final lower = query.toLowerCase();
    return _places.where((p) =>
      p.name.toLowerCase().contains(lower) ||
      p.hindiName.contains(query) ||
      p.location.toLowerCase().contains(lower) ||
      p.state.toLowerCase().contains(lower) ||
      p.category.displayName.toLowerCase().contains(lower) ||
      p.dynastyOrPatron.toLowerCase().contains(lower)
    ).toList();
  }
